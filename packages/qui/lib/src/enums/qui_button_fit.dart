/// Controls the width sizing behavior of QUI buttons.
///
/// [QuiButtonFit.fit] shrink-wraps the button to its content.
/// [QuiButtonFit.expand] fills the available horizontal width.
enum QuiButtonFit {
  /// The button shrink-wraps to its content.
  fit,

  /// The button expands to fill the available horizontal width.
  expand,
}
